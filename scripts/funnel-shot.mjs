import { chromium } from "playwright";
const base = process.env.BASE_URL || "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
for (const [label, vp] of [["phone", { width: 390, height: 844 }], ["desktop", { width: 1440, height: 900 }]]) {
  const ctx = await browser.newContext({ viewport: vp, isMobile: label === "phone", hasTouch: label === "phone" });
  const page = await ctx.newPage();
  const errors = [];
  page.on("console", (m) => m.type() === "error" && !m.text().includes("TUNNEL") && errors.push(m.text()));
  page.on("pageerror", (e) => errors.push(String(e)));
  await page.goto(base + "/", { waitUntil: "networkidle" });
  await page.getByPlaceholder(/Type a product/).fill("cerave pm");
  await page.waitForTimeout(300);
  await page.screenshot({ path: `.shots/f1-search-${label}.png` });
  await page.keyboard.press("Enter");
  await page.getByTestId("try-example").click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: `.shots/f2-skin-${label}.png` });
  await page.getByTestId("skin-combination").click();
  await page.waitForTimeout(1600);
  await page.screenshot({ path: `.shots/f3-work-${label}.png` });
  await page.getByTestId("locked-result").waitFor({ timeout: 20000 });
  await page.waitForTimeout(800);
  await page.screenshot({ path: `.shots/f4-locked-${label}.png`, fullPage: false });
  await page.getByTestId("locked-result").screenshot({ path: `.shots/f4b-locked-${label}.png` });
  await page.getByTestId("unlock-button").click();
  await page.waitForTimeout(900);
  await page.screenshot({ path: `.shots/f5-auth-${label}.png` });
  await page.locator("#auth-email").fill(`test-${label}-${Date.now()}@example.com`);
  await page.locator("#auth-password").fill("supersecret123");
  await page.getByTestId("auth-submit").click();
  await page.getByTestId("paywall").waitFor({ timeout: 15000 });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: `.shots/f6-paywall-${label}.png` });
  await page.getByTestId("paywall-continue").click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `.shots/f7-after-continue-${label}.png` });
  await page.getByTestId("paywall-close").click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `.shots/f8-closed-${label}.png` });
  console.log(label, errors.length ? "ERRORS: " + errors.join(" | ") : "clean");
  await ctx.close();
}
await browser.close();
